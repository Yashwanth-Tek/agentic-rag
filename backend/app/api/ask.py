"""Ask: one question in, Server-Sent Events out.

Events: `run` (limits) → `activity`… (what the agent is doing, generated by the application,
never model text) → exactly one `result` or `error`. The agent runs on a worker thread; closing
the connection cancels it.
"""

import asyncio
import json
import logging
import threading
from collections.abc import AsyncIterator
from typing import Any

from fastapi import APIRouter, Request
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

from app.agent.service import answer_question
from app.errors import AppError

router = APIRouter(prefix="/api", tags=["ask"])
log = logging.getLogger(__name__)

PING_INTERVAL_SECONDS = 10


class AskRequest(BaseModel):
    question: str = Field(min_length=1, max_length=2000)


@router.post("/ask")
async def ask(body: AskRequest, request: Request) -> StreamingResponse:
    question = body.question.strip()
    if not question:
        raise AppError("INVALID_REQUEST", "Please enter a question.")
    state = request.app.state
    settings = state.settings
    loop = asyncio.get_running_loop()
    queue: asyncio.Queue[dict[str, Any]] = asyncio.Queue()
    cancel = threading.Event()

    def emit(event: dict[str, Any]) -> None:
        loop.call_soon_threadsafe(queue.put_nowait, event)

    def work() -> None:
        answer_question(
            question,
            cancel=cancel,
            emit=emit,
            repo=state.repo.read_only(),
            embedder=state.embedder,
            llm=state.llm,
            settings=settings,
        )

    worker = loop.run_in_executor(None, work)

    async def events() -> AsyncIterator[str]:
        try:
            yield _sse(
                {
                    "event": "run",
                    "limits": {
                        "max_tool_calls": settings.max_tool_calls,
                        "max_agent_time_seconds": settings.max_agent_time_seconds,
                    },
                }
            )
            while True:
                try:
                    event = await asyncio.wait_for(queue.get(), timeout=PING_INTERVAL_SECONDS)
                except TimeoutError:
                    if worker.done() and queue.empty():
                        exc = worker.exception()
                        log.error("agent worker ended without a result", exc_info=exc)
                        message = "Something went wrong on our side. Please try again."
                        yield _sse({"event": "error", "code": "INTERNAL_ERROR", "message": message})
                        return
                    yield ": ping\n\n"  # keeps the connection alive during long requests
                    continue
                yield _sse(event)
                if event["event"] in ("result", "error"):
                    return
        finally:
            cancel.set()

    return StreamingResponse(
        events(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


def _sse(event: dict[str, Any]) -> str:
    payload = {key: value for key, value in event.items() if key != "event"}
    return f"event: {event['event']}\ndata: {json.dumps(payload)}\n\n"
